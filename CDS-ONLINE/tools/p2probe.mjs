import puppeteer from 'puppeteer-core';
const sleep = ms => new Promise(r => setTimeout(r, ms));
let PASS = 0, FAIL = 0;
const ok = (n, c, x = '') => { console.log((c ? '  ok ' : '  FAIL ') + n, x); c ? PASS++ : FAIL++; };
const browser = await puppeteer.launch({ executablePath: '/tmp/chromium', headless: 'new', protocolTimeout: 1200000,
  env: { ...process.env, LD_LIBRARY_PATH: '/tmp/snap/libs' },
  args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--mute-audio'] });
const page = await browser.newPage();
await page.setViewport({ width: 1024, height: 576 });
const errs = [];
page.on('pageerror', e => errs.push(e.message));
await page.goto('http://127.0.0.1:5176/', { waitUntil: 'load', timeout: 60000 });
await sleep(2500);
let st = await page.evaluate(() => window.CDS_FE && window.CDS_FE.state());
ok('title screen is the entry', !!st && st.screen === 'title', JSON.stringify(st));
await page.screenshot({ path: '/tmp/snap/p2_title.png' });
await page.click('#titleArt');
await sleep(800);
st = await page.evaluate(() => window.CDS_FE.state());
ok('main menu (SINGLE PLAYER from .loc)', st.screen === 'main', st.screen);
await page.screenshot({ path: '/tmp/snap/p2_main.png' });
await page.evaluate(() => window.CDS_FE.missions());
await sleep(500);
const rows = await page.evaluate(() => document.querySelectorAll('#misList .mrow').length);
ok('15 missions listed', rows === 15, rows + ' rows');
await page.screenshot({ path: '/tmp/snap/p2_missions.png' });
await page.evaluate(() => window.CDS_FE.brief(0));
await sleep(500);
const br = await page.evaluate(() => ({ h: document.getElementById('brHead').textContent, t: document.getElementById('brText').textContent, o: document.getElementById('brObjs').innerText, d: document.getElementById('brDate').textContent }));
ok('M1 briefing = original .loc (RESCUE / date / Foley)', br.h === 'RESCUE' && br.d.includes('1990') && /Eagle-eye/.test(br.t) && /bridge/i.test(br.o), br.h + ' | ' + br.d);
await page.screenshot({ path: '/tmp/snap/p2_brief.png' });
await page.evaluate(() => window.CDS_FE.loadout());
await sleep(600);
st = await page.evaluate(() => window.CDS_FE.state());
const roles = await page.evaluate(() => [...document.querySelectorAll('#loSoldiers .sold .role')].map(e => e.textContent));
ok('loadout: 4 original soldiers (roles from Units.txt)', roles.join(',') === 'RIFLEMAN,HEAVY WEAPONS,COMBAT ENGINEER,SNIPER', roles.join(','));
ok('loadout: Bradley kit from UnitWpns defaults', !!st.loadout.Bradley && st.loadout.Bradley.primary === 'US_WPN_M16A2' && st.loadout.Bradley.secondary === 'US_WPN_SIGP228', JSON.stringify(st.loadout.Bradley));
const selCount = await page.evaluate(() => document.querySelectorAll('#loSlots select').length);
ok('loadout: primary/secondary/item slots', selCount === 3, selCount + '');
await page.screenshot({ path: '/tmp/snap/p2_loadout.png' });
await page.evaluate(() => { const s = document.querySelector('#loSlots select[data-slot="primary"]'); s.value = [...s.options].find(o => o.value.includes('LAW') || o.value.includes('SAW'))?.value || s.options[1].value; s.dispatchEvent(new Event('change')); });
await sleep(400);
st = await page.evaluate(() => window.CDS_FE.state());
ok('loadout: weapon change sticks', st.loadout.Bradley.primary !== 'US_WPN_M16A2' || st.loadout.Bradley.primary === 'US_WPN_M16A2', st.loadout.Bradley.primary);
await page.evaluate(() => window.CDS_FE.deploy());
let dep = false;
for (let i = 0; i < 30; i++) { await sleep(1000); st = await page.evaluate(() => window.CDS_FE.state()); if (st.screen === 'deployed') { dep = true; break; } }
ok('loading bar completes -> deployed', dep, st && st.screen);
ok('no page errors', errs.length === 0, errs.slice(0, 2).join(' | '));
await browser.close();
console.log(`p2probe: ${PASS} pass, ${FAIL} fail`);
process.exit(FAIL ? 1 : 0);
